def s2t(text):
    """简体 → 繁体：opencc 词汇级优先，回退字表。"""
    if _HAS_OPENCC:
        return _cc_s2t.convert(text)
    return text.translate(_TRANS)


def t2s(text):
    """繁体 → 简体：opencc 词汇级优先，回退字表。"""
    if _HAS_OPENCC:
        return _cc_t2s.convert(text)
    return text.translate(_REV_TRANS)


class ZhConvertPanel(QWidget):
    """简繁转换面板。"""

    def __init__(self, parent=None):
        super().__init__(parent)
        v = QVBoxLayout(self)
        self.ed_in = QPlainTextEdit()
        self.ed_in.setPlaceholderText(
            tr("输入要转换的文本…", "Enter text to convert…"))
        v.addWidget(self.ed_in, 1)

        row = QHBoxLayout()
        row.setSpacing(8)
        btn_t = PrimaryPushButton(
            tr("简体 → 繁体", "Simplified → Traditional"))
        btn_t.clicked.connect(self._to_trad)
        row.addWidget(btn_t)
        btn_s = PrimaryPushButton(
            tr("繁体 → 简体", "Traditional → Simplified"))
        btn_s.clicked.connect(self._to_simp)
        row.addWidget(btn_s)
        row.addStretch(1)
        v.addLayout(row)

        self.ed_out = QPlainTextEdit()
        self.ed_out.setReadOnly(True)
        v.addWidget(self.ed_out, 1)
        self._apply_theme()
        from gui_qt.components import design_system as ds
        ds.bind_theme(self, self._apply_theme)

    def _apply_theme(self):
        from gui_qt.components import design_system as ds
        t = ds.tokens()
        self.setStyleSheet(
            f"QPlainTextEdit {{ background: {t['card_bg']};"
            f" color: {t['ink']}; border: 1px solid {t['border']};"
            f" border-radius: 6px; padding: 4px; font-size: 13px; }}")

    def _to_trad(self):
        self.ed_out.setPlainText(s2t(self.ed_in.toPlainText()))

    def _to_simp(self):
        self.ed_out.setPlainText(t2s(self.ed_in.toPlainText()))


