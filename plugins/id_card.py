def parse_id_card(card):
    """解析 18 位身份证。返回 (ok, 文本或错误)。"""
    card = card.strip()
    if len(card) != 18:
        return False, t("长度必须为 18 位")
    if not re.fullmatch(r"\d{17}[\dXx]", card):
        return False, t("格式错误：前 17 位数字，末位数字或 X")
    # 校验码
    total = sum(int(card[i]) * _WEIGHTS[i] for i in range(17))
    expect = _CHECK_CODES[total % 11]
    if card[-1].upper() != expect:
        return False, t("校验失败：末位应为 {expect}")
    # 出生日期
    try:
        birth = datetime.datetime.strptime(card[6:14], "%Y%m%d")
    except ValueError:
        return False, t("出生日期无效")
    # 地区
    prov = _PROVINCES.get(card[:2], t("未知省"))
    city = _CITIES.get(card[:4], "")
    region = f"{prov}{city}" if city else f"{prov}（具体城市未收录）"
    gender = t("女") if int(card[16]) % 2 == 0 else t("男")
    today = datetime.date.today()
    age = today.year - birth.year - (
        (today.month, today.day) < (birth.month, birth.day))
    lines = [
        t("校验：✓ 通过（末位 {expect}）"),
        f"地区：{region}（{card[:6]}）",
        f"出生：{birth:%Y 年 %m 月 %d 日}（{age} 岁）",
        t("性别：{gender}"),
        f"星座：{_zodiac(birth.month, birth.day)}",
    ]
    return True, "\n".join(lines)


def _zodiac(month, day):
    signs = [t("摩羯"), t("水瓶"), t("双鱼"), t("白羊"), t("金牛"), t("双子"), t("巨蟹"),
             t("狮子"), t("处女"), t("天秤"), t("天蝎"), t("射手")]
    boundary = [20, 19, 21, 20, 21, 22, 23, 23, 23, 24, 23, 22]
    idx = month - 1
    if day < boundary[idx]:
        idx = (idx - 1) % 12
    return signs[idx] + "座"


class IdCardPanel(QWidget):
    """身份证解析面板。"""

    def __init__(self, parent=None):
        super().__init__(parent)
        v = QVBoxLayout(self)
        self.ed_in = QLineEdit()
        self.ed_in.setPlaceholderText(t("输入 18 位身份证号码…"))
        self.ed_in.returnPressed.connect(self._run)
        v.addWidget(self.ed_in)

        row = QHBoxLayout()
        btn = PrimaryPushButton(t("解析"))
        btn.clicked.connect(self._run)
        row.addWidget(btn)
        row.addStretch(1)
        v.addLayout(row)

        self.ed_out = QPlainTextEdit()
        self.ed_out.setReadOnly(True)
        v.addWidget(self.ed_out, 1)
        self._apply_theme()
        from gui_qt.components import design_system as ds
        ds.bind_theme(self, self._apply_theme)

    def _apply_theme(self):
        from gui_qt.components import design_system as ds
        t = ds.tokens()
        self.setStyleSheet(
            f"QLineEdit, QPlainTextEdit {{ background: {t['card_bg']};"
            f" color: {t['ink']}; border: 1px solid {t['border']};"
            f" border-radius: 6px; padding: 4px; font-size: 13px; }}")

    def _run(self):
        ok, result = parse_id_card(self.ed_in.text())
        self.ed_out.setPlainText(result if ok else f"✗ {result}")


